#!/usr/bin/env python3
"""Generate per-pair Rust files invoking the lms_impl! macro, and the
typecode routing table over them.

Each pair file is a thin shim — it imports Service and calls the macro
with the pair's hash adapter, parameters, typecodes and its
`Service::Lms…Verify` discriminant. The macro emits the verifier for
that exact pair.

`dispatch_table.rs` maps each pair's (LMS, LM-OTS) typecodes to that
pair's `verify`. It is written from the same typecode tables as the pair
files, always for all 80 pairs, whatever families are selected.

The per-(N, W) values U, V, P and LS are the RFC 8554 Appendix B
formulas evaluated for each pair and written out as literals (no
runtime computation).

Usage: `python3 lms_gen_pairs.py [family ...]`, where a family is one of
sha256_m32, sha256_m24, shake_m32, shake_m24. With no argument, all
four families are written.
"""
import sys
import os
from pathlib import Path

# Repo root, derived from this script's own location so the tool runs from any
# checkout. Override with OXICRYPT_ROOT when running against a worktree.
REPO_ROOT = Path(os.environ.get("OXICRYPT_ROOT", Path(__file__).resolve().parents[1]))
SRC_DIR = REPO_ROOT / "crates" / "oxicrypt-lms" / "src"

# (N, W) → (U, V, P, LS) per RFC 8554 Appendix B. P matches the p column
# of SP 800-208 §4 Tables 1, 3, 5 and 7.
UV_TABLE = {
    (32, 1): (256, 9, 265, 7),
    (32, 2): (128, 5, 133, 6),
    (32, 4): (64, 3, 67, 4),
    (32, 8): (32, 2, 34, 0),
    (24, 1): (192, 8, 200, 8),
    (24, 2): (96, 5, 101, 6),
    (24, 4): (48, 3, 51, 4),
    (24, 8): (24, 2, 26, 0),
}

# LMS typecodes. SP 800-208 §4.1 Table 2 gives the SHA-256/M32 values and
# Tables 4, 6 and 8 leave the others TBD; every value here is the typecode
# the NIST ACVP sigVer public keys and signatures carry for that set.
# (family, M, H) → 32-bit typecode.
LMS_TYPECODES = {
    ("sha256", 32, 5):  0x05,
    ("sha256", 32, 10): 0x06,
    ("sha256", 32, 15): 0x07,
    ("sha256", 32, 20): 0x08,
    ("sha256", 32, 25): 0x09,
    ("sha256", 24, 5):  0x0a,
    ("sha256", 24, 10): 0x0b,
    ("sha256", 24, 15): 0x0c,
    ("sha256", 24, 20): 0x0d,
    ("sha256", 24, 25): 0x0e,
    ("shake",  32, 5):  0x0f,
    ("shake",  32, 10): 0x10,
    ("shake",  32, 15): 0x11,
    ("shake",  32, 20): 0x12,
    ("shake",  32, 25): 0x13,
    ("shake",  24, 5):  0x14,
    ("shake",  24, 10): 0x15,
    ("shake",  24, 15): 0x16,
    ("shake",  24, 20): 0x17,
    ("shake",  24, 25): 0x18,
}

# LM-OTS typecodes. SP 800-208 §4.1 Table 1 gives the SHA-256/N32 values
# and Tables 3, 5 and 7 leave the others TBD; every value here is the
# typecode the NIST ACVP sigVer public keys and signatures carry for that set.
# (family, N, W) → 32-bit typecode.
LMOTS_TYPECODES = {
    ("sha256", 32, 1): 0x01,
    ("sha256", 32, 2): 0x02,
    ("sha256", 32, 4): 0x03,
    ("sha256", 32, 8): 0x04,
    ("sha256", 24, 1): 0x05,
    ("sha256", 24, 2): 0x06,
    ("sha256", 24, 4): 0x07,
    ("sha256", 24, 8): 0x08,
    ("shake",  32, 1): 0x09,
    ("shake",  32, 2): 0x0a,
    ("shake",  32, 4): 0x0b,
    ("shake",  32, 8): 0x0c,
    ("shake",  24, 1): 0x0d,
    ("shake",  24, 2): 0x0e,
    ("shake",  24, 4): 0x0f,
    ("shake",  24, 8): 0x10,
}

ADAPTER = {
    ("sha256", 32): "Sha256N32",
    ("sha256", 24): "Sha256N24",
    ("shake",  32): "Shake256N32",
    ("shake",  24): "Shake256N24",
}

VARIANT_FAMILY = {
    ("sha256", 32): "Sha256M32",
    ("sha256", 24): "Sha256M24",
    ("shake",  32): "ShakeM32",
    ("shake",  24): "ShakeM24",
}

ALL_FAMILIES = ["sha256_m32", "sha256_m24", "shake_m32", "shake_m24"]
ALLOWED_FAMILIES = sys.argv[1:] if len(sys.argv) > 1 else ALL_FAMILIES
_unknown = [f for f in ALLOWED_FAMILIES if f not in ALL_FAMILIES]
if _unknown:
    sys.exit(f"unknown family {_unknown}; expected any of {ALL_FAMILIES}")

TEMPLATE = '''//! {pair_human} instantiation.
//!
//! Parameters: hash = {hash_human}, N = {n}, H = {h} ({signatures}
//! signatures), W = {w} (Winternitz). Derived (RFC 8554 Appendix B):
//! U = {u}, V = {v}, P = {p}, LS = {ls}.
//!
//! Written by `scripts/lms_gen_pairs.py`; the `lms_impl!` invocation
//! below emits the verifier. External KAT grounding: the NIST ACVP
//! sigVer test group for this pair, from
//! `usnistgov/ACVP-Server @ 3611942e`, run by
//! `tests/acvp_sigver_all_pairs.rs`.

use oxicrypt_module::Service;

crate::lms_impl::lms_impl! {{
    hasher = crate::hash::{adapter};
    n = {n};
    h = {h};
    w = {w};
    u = {u};
    v = {v};
    p = {p};
    ls = {ls};
    lms_type = 0x0000_{lms_type:04x};
    lmots_type = 0x0000_{lmots_type:04x};
    svc_verify = Service::{variant}Verify;
}}
'''

DISPATCH_TEMPLATE = '''//! Routing table from an (LMS, LM-OTS) typecode pair to that pair's
//! `verify`, one arm per SP 800-208 §4.1–§4.4 pair.
//!
//! Generated by `scripts/lms_gen_pairs.py` from the typecode tables that
//! generate the per-pair modules. Regenerate rather than edit.

use crate::dispatch::{{VerifyAnyError, route}};

/// Verify through the pair whose typecodes are `lms_type` and
/// `lmots_type`, or refuse as [`VerifyAnyError::Unroutable`] when no pair
/// carries them.
pub(crate) fn route_by_typecode(
    lms_type: u32,
    lmots_type: u32,
    pk: &[u8],
    msg: &[u8],
    sig: &[u8],
) -> Result<(), VerifyAnyError> {{
    match (lms_type, lmots_type) {{
{arms}        _ => Err(VerifyAnyError::Unroutable),
    }}
}}
'''

DISPATCH_ARM = '''        (0x0000_{lms_type:04x}, 0x0000_{lmots_type:04x}) => route(crate::{slug}::verify, pk, msg, sig),
'''


def all_pairs():
    """Every (slug, LMS typecode, LM-OTS typecode) of the grid, in table order."""
    for (fam, m, h), lms_type in LMS_TYPECODES.items():
        for w in (1, 2, 4, 8):
            yield f"lms_{fam}_m{m}_h{h}_w{w}", lms_type, LMOTS_TYPECODES[(fam, m, w)]


def write_dispatch_table():
    pairs = list(all_pairs())
    keys = [(lms, lmots) for _, lms, lmots in pairs]
    if len(set(keys)) != len(keys):
        sys.exit("two pairs share a typecode pair")
    arms = "".join(
        DISPATCH_ARM.format(slug=slug, lms_type=lms, lmots_type=lmots)
        for slug, lms, lmots in pairs
    )
    out = SRC_DIR / "dispatch_table.rs"
    out.write_text(DISPATCH_TEMPLATE.format(arms=arms))
    return len(pairs)


def main():
    pairs_written = []
    for (fam, m, h), lms_type in LMS_TYPECODES.items():
        if f"{fam}_m{m}" not in ALLOWED_FAMILIES:
            continue
        for w in (1, 2, 4, 8):
            lmots_type = LMOTS_TYPECODES[(fam, m, w)]
            u, v, p, ls = UV_TABLE[(m, w)]
            slug = f"lms_{fam}_m{m}_h{h}_w{w}"
            adapter = ADAPTER[(fam, m)]
            hash_human = {"sha256": "SHA-256", "shake": "SHAKE-256"}[fam]
            fam_caps = {"sha256": "SHA256", "shake": "SHAKE"}[fam]
            pair_human = f"LMS_{fam_caps}_M{m}_H{h} / LMOTS_{fam_caps}_N{m}_W{w}"
            content = TEMPLATE.format(
                pair_human=pair_human,
                hash_human=hash_human,
                adapter=adapter,
                variant=f"Lms{VARIANT_FAMILY[(fam, m)]}H{h}W{w}",
                n=m,
                h=h,
                w=w,
                u=u,
                v=v,
                p=p,
                ls=ls,
                lms_type=lms_type,
                lmots_type=lmots_type,
                signatures=2**h,
            )
            out = SRC_DIR / f"{slug}.rs"
            out.write_text(content)
            pairs_written.append(slug)

    print(f"families={ALLOWED_FAMILIES}")
    print(f"pair files written: {len(pairs_written)}")
    if not pairs_written:
        sys.exit("no pair files written")
    for slug in sorted(pairs_written):
        print(f"  {slug}")
    print(f"dispatch_table.rs routes: {write_dispatch_table()}")


if __name__ == "__main__":
    main()
