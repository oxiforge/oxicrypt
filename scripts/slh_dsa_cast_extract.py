#!/usr/bin/env python3
"""Extract the SLH-DSA power-up self-test vectors from NIST ACVP-Server data.

Regenerates:

  - vendor/nist/acvp-server/gen-val/json-files/SLH-DSA-keyGen-FIPS205/cast-slice.json
  - vendor/nist/acvp-server/gen-val/json-files/SLH-DSA-sigGen-FIPS205/cast-slice.json
  - crates/oxicrypt-slh-dsa/src/cast_vectors.rs

Two modes:

`slice KEYGEN_JSON SIGGEN_JSON` reads the ACVP-Server
`SLH-DSA-keyGen-FIPS205/internalProjection.json` and
`SLH-DSA-sigGen-FIPS205/internalProjection.json` at the commit pinned in
vendor/nist/MANIFEST.toml and writes the two `cast-slice.json` files. The
full sigGen projection is tens of megabytes, so only the selected test cases
are vendored. It prints the SHA-256 of each source file and each slice for
the MANIFEST.toml rows.

`cast` reads the two vendored slices and writes `cast_vectors.rs`.

Selection, for SLH-DSA-SHA2-128f and SLH-DSA-SHAKE-128f (the set of each
hash family with the lowest-height trees: XMSS subtree height h' = 3 and
FORS tree height a = 6):

  - keyGen: the first test case of the parameter set's group.
  - sigGen: the deterministic, internal-interface group (FIPS 205
    Algorithm 19, no context string, no additional randomness), and in it
    the test case with the shortest message, lowest tcId on a tie. The same
    test case supplies the verification vector: NIST's signature, its
    public key and its message.
"""
import hashlib
import json
import os
import re
import sys
from pathlib import Path

REPO_ROOT = Path(os.environ.get("OXICRYPT_ROOT", Path(__file__).resolve().parents[1]))
JSON_FILES = REPO_ROOT / "vendor" / "nist" / "acvp-server" / "gen-val" / "json-files"
KEYGEN_SLICE = JSON_FILES / "SLH-DSA-keyGen-FIPS205" / "cast-slice.json"
SIGGEN_SLICE = JSON_FILES / "SLH-DSA-sigGen-FIPS205" / "cast-slice.json"
VECTORS_RS = REPO_ROOT / "crates" / "oxicrypt-slh-dsa" / "src" / "cast_vectors.rs"
MANIFEST = REPO_ROOT / "vendor" / "nist" / "MANIFEST.toml"

# (Rust module name in cast_vectors.rs, ACVP parameterSet)
PARAMETER_SETS = [
    ("sha2_128f", "SLH-DSA-SHA2-128f"),
    ("shake_128f", "SLH-DSA-SHAKE-128f"),
]


def pinned_commit() -> str:
    m = re.search(r'^\[acvp_server\]\s*\ncommit = "([0-9a-f]{40})"', MANIFEST.read_text(), re.M)
    if not m:
        raise SystemExit(f"no [acvp_server] commit in {MANIFEST}")
    return m.group(1)


def sha256_of(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def load_projection(path: Path, mode: str) -> dict:
    data = json.loads(path.read_text())
    if data.get("algorithm") != "SLH-DSA" or data.get("mode") != mode:
        raise SystemExit(f"{path}: not an SLH-DSA {mode} projection")
    return data


def pick_keygen(doc: dict, parameter_set: str):
    groups = [g for g in doc["testGroups"] if g.get("parameterSet") == parameter_set]
    if len(groups) != 1:
        raise SystemExit(f"keyGen: expected one {parameter_set} group, found {len(groups)}")
    g = groups[0]
    return g, g["tests"][0]


def pick_siggen(doc: dict, parameter_set: str):
    groups = [
        g
        for g in doc["testGroups"]
        if g.get("parameterSet") == parameter_set
        and g.get("deterministic") is True
        and g.get("signatureInterface") == "internal"
    ]
    if len(groups) != 1:
        raise SystemExit(f"sigGen: expected one deterministic internal {parameter_set} group, found {len(groups)}")
    g = groups[0]
    tests = [t for t in g["tests"] if "additionalRandomness" not in t and "context" not in t]
    if not tests:
        raise SystemExit(f"sigGen: no usable test case for {parameter_set}")
    tc = min(tests, key=lambda t: (len(t["message"]), t["tcId"]))
    return g, tc


def group_header(g: dict) -> dict:
    return {k: v for k, v in g.items() if k != "tests"}


def slice_(keygen_path: Path, siggen_path: Path):
    commit = pinned_commit()
    keygen = load_projection(keygen_path, "keyGen")
    siggen = load_projection(siggen_path, "sigGen")
    outputs = [
        (KEYGEN_SLICE, keygen_path, "keyGen", keygen, pick_keygen),
        (SIGGEN_SLICE, siggen_path, "sigGen", siggen, pick_siggen),
    ]
    for out_path, src_path, mode, doc, pick in outputs:
        selected, groups = [], []
        for _, parameter_set in PARAMETER_SETS:
            g, tc = pick(doc, parameter_set)
            selected.append({"parameterSet": parameter_set, "tgId": g["tgId"], "tcId": tc["tcId"]})
            groups.append({**group_header(g), "tests": [tc]})
        slice_doc = {
            "_source": {
                "repo": "usnistgov/ACVP-Server",
                "commit": commit,
                "path": f"gen-val/json-files/SLH-DSA-{mode}-FIPS205/internalProjection.json",
                "sha256": sha256_of(src_path),
                "selected": selected,
                "note": "power-up self-test vectors; generated by scripts/slh_dsa_cast_extract.py",
            },
            "algorithm": "SLH-DSA",
            "mode": mode,
            "revision": doc["revision"],
            "testGroups": groups,
        }
        out_path.write_text(json.dumps(slice_doc, indent=2) + "\n")
        print(f"wrote {out_path.relative_to(REPO_ROOT)} sha256={sha256_of(out_path)}")
        print(f"  source sha256={sha256_of(src_path)}")
        for s in selected:
            print(f"  {s['parameterSet']}: tgId={s['tgId']} tcId={s['tcId']}")


# Bytes per line: the most rustfmt keeps on one line at this indent.
ROW = 15


def rust_array(name: str, doc: str, data: bytes) -> str:
    head = f"    pub(crate) static {name}: [u8; {len(data)}] = ["
    one_line = head + ", ".join(f"0x{b:02x}" for b in data) + "];"
    if len(one_line) <= 100:
        return f"    /// {doc}\n{one_line}"
    lines = [f"    /// {doc}", head]
    for i in range(0, len(data), ROW):
        lines.append("        " + " ".join(f"0x{b:02x}," for b in data[i : i + ROW]))
    lines.append("    ];")
    return "\n".join(lines)


def cast():
    keygen = json.loads(KEYGEN_SLICE.read_text())
    siggen = json.loads(SIGGEN_SLICE.read_text())
    commit = keygen["_source"]["commit"]
    if siggen["_source"]["commit"] != commit or commit != pinned_commit():
        raise SystemExit("slices and MANIFEST.toml name different ACVP-Server commits")
    kg = {g["parameterSet"]: g for g in keygen["testGroups"]}
    sg = {g["parameterSet"]: g for g in siggen["testGroups"]}

    out = [
        "//! Power-up self-test vectors for SLH-DSA.",
        "//!",
        "//! Source: NIST ACVP-Server, `gen-val/json-files/SLH-DSA-keyGen-FIPS205/` and",
        "//! `SLH-DSA-sigGen-FIPS205/` `internalProjection.json`, at commit",
        f"//! `{commit}`, pinned in `vendor/nist/MANIFEST.toml`.",
        "//! The selected test cases are vendored as `cast-slice.json` in each",
        "//! directory. Generated by `scripts/slh_dsa_cast_extract.py cast`.",
        "//!",
        "//! | Parameter set | keyGen tgId / tcId | sigGen tgId / tcId |",
        "//! |---|---|---|",
    ]
    picks = []
    for module, parameter_set in PARAMETER_SETS:
        k, s = kg[parameter_set], sg[parameter_set]
        if s.get("deterministic") is not True or s.get("signatureInterface") != "internal":
            raise SystemExit(f"{parameter_set}: sigGen group is not deterministic and internal")
        kt, st = k["tests"][0], s["tests"][0]
        out.append(f"//! | {parameter_set} | {k['tgId']} / {kt['tcId']} | {s['tgId']} / {st['tcId']} |")
        picks.append((module, parameter_set, k, kt, s, st))
    out += [
        "//!",
        "//! The sigGen test case also supplies the verification vector: NIST's",
        "//! signature must verify under the test case's public key and message.",
        "//!",
        "//! The values are compiled into the module rather than read at run time.",
        "//! ISO/IEC 19790:2012 §7.10.1 requires a self-test to reach its verdict",
        "//! without externally provided test vectors or expected results; a constant",
        "//! linked into the binary is inside the cryptographic boundary, a file read",
        "//! during the test would not be. Nothing here was produced by this crate.",
    ]
    for module, parameter_set, k, kt, s, st in picks:
        kid = f"tgId {k['tgId']}, tcId {kt['tcId']}"
        sid = f"tgId {s['tgId']}, tcId {st['tcId']}"
        fields = [
            ("KEYGEN_SK_SEED", f"keyGen SK.seed, {kid}.", kt["skSeed"]),
            ("KEYGEN_SK_PRF", f"keyGen SK.prf, {kid}.", kt["skPrf"]),
            ("KEYGEN_PK_SEED", f"keyGen PK.seed, {kid}.", kt["pkSeed"]),
            ("KEYGEN_SK", f"keyGen expected private key, {kid}.", kt["sk"]),
            ("KEYGEN_PK", f"keyGen expected public key, {kid}.", kt["pk"]),
            ("SIG_SK", f"sigGen private key, {sid}.", st["sk"]),
            ("SIG_PK", f"sigGen public key, {sid}.", st["pk"]),
            ("SIG_MSG", f"sigGen message, {sid}.", st["message"]),
            ("SIG", f"sigGen expected signature, {sid}.", st["signature"]),
        ]
        out += ["", f"/// {parameter_set}.", f"pub(crate) mod {module} {{"]
        out.append("\n\n".join(rust_array(name, doc, bytes.fromhex(hx)) for name, doc, hx in fields))
        out.append("}")
    VECTORS_RS.write_text("\n".join(out) + "\n")
    print(f"wrote {VECTORS_RS.relative_to(REPO_ROOT)}")


def main():
    args = sys.argv[1:]
    if args[:1] == ["slice"] and len(args) == 3:
        slice_(Path(args[1]), Path(args[2]))
    elif args == ["cast"]:
        cast()
    else:
        sys.exit("usage: slh_dsa_cast_extract.py slice KEYGEN_JSON SIGGEN_JSON | cast")


if __name__ == "__main__":
    main()
