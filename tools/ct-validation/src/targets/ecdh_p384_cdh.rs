//! ct-validation target: [`oxicrypt_ecdh::compute_shared_secret_p384_internal`].
//!
//! ECDH-P384-CDH shares its scalar-multiplication core with P-384
//! ECDSA sign; this target exists mainly as a smoke check to make
//! sure the gated entry point and SP 800-56Ar3 §5.6.2.3.3
//! public-key validation don't add data-dependent branches on top
//! of the already-validated scalar mul. We pre-validate the peer
//! public key by using RFC 5903 §8.2's fixture (same one the
//! ECDH P-384 power-up KAT uses) so every measured call goes
//! through the same success path; only the private scalar `d`
//! changes between fixed and random classes.

use crate::measure::{run_target, RunConfig};
use crate::stats::VerdictReport;
use oxicrypt_ecdh::{compute_shared_secret_p384_internal, P384_PRIVATE_KEY_LEN, P384_PUBLIC_KEY_LEN};

/// RFC 5903 §8.2 responder public key `Q_r`.
const PEER_PK: [u8; P384_PUBLIC_KEY_LEN] = [
    0x04,
    0xe5, 0x58, 0xdb, 0xef, 0x53, 0xee, 0xcd, 0xe3, 0xd3, 0xfc, 0xcf, 0xc1, 0xae, 0xa0, 0x8a, 0x89,
    0xa9, 0x87, 0x47, 0x5d, 0x12, 0xfd, 0x95, 0x0d, 0x83, 0xcf, 0xa4, 0x17, 0x32, 0xbc, 0x50, 0x9d,
    0x0d, 0x1a, 0xc4, 0x3a, 0x03, 0x36, 0xde, 0xf9, 0x6f, 0xda, 0x41, 0xd0, 0x77, 0x4a, 0x35, 0x71,
    0xdc, 0xfb, 0xec, 0x7a, 0xac, 0xf3, 0x19, 0x64, 0x72, 0x16, 0x9e, 0x83, 0x84, 0x30, 0x36, 0x7f,
    0x66, 0xee, 0xbe, 0x3c, 0x6e, 0x70, 0xc4, 0x16, 0xdd, 0x5f, 0x0c, 0x68, 0x75, 0x9d, 0xd1, 0xff,
    0xf8, 0x3f, 0xa4, 0x01, 0x42, 0x20, 0x9d, 0xff, 0x5e, 0xaa, 0xd9, 0x6d, 0xb9, 0xe6, 0x38, 0x6c,
];

/// Fixed private scalar — any canonical non-zero scalar works.
const FIXED_D: [u8; P384_PRIVATE_KEY_LEN] = [
    0x11, 0x22, 0x33, 0x44, 0x55, 0x66, 0x77, 0x88, 0x99, 0xaa, 0xbb, 0xcc, 0xdd, 0xee, 0xff, 0x00,
    0x10, 0x20, 0x30, 0x40, 0x50, 0x60, 0x70, 0x80, 0x90, 0xa0, 0xb0, 0xc0, 0xd0, 0xe0, 0xf0, 0x01,
    0xab, 0xcd, 0xef, 0x01, 0x23, 0x45, 0x67, 0x89, 0xfe, 0xdc, 0xba, 0x98, 0x76, 0x54, 0x32, 0x10,
];

/// Measure [`compute_shared_secret_p384_internal`] under the
/// paired-class protocol and return the cropped t-test report.
pub fn run(cfg: &RunConfig) -> VerdictReport {
    let target = Box::new(|secret: &[u8]| {
        let mut d = [0u8; P384_PRIVATE_KEY_LEN];
        d.copy_from_slice(secret);
        // Canonicalize: keep top byte zero so the scalar is < 2^376 < n,
        // guaranteeing from_bytes accepts it.
        d[0] = 0;
        d[47] |= 1;
        let r = compute_shared_secret_p384_internal(&d, &PEER_PK);
        std::hint::black_box(r);
    });

    run_target("ecdh_p384_cdh", &FIXED_D, target, cfg)
}
