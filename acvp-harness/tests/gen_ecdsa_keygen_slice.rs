#[test]
#[ignore]
fn generate_ecdsa_keygen_slice() {
    let mut tests_json = Vec::new();
    for (i, d) in SCALARS.iter().enumerate() {
        let pk = oxicrypt_ecdsa::p256_ecdsa::derive_public_key_internal(d)
            .unwrap_or_else(|| panic!("derive_public_key_internal failed for test {i}"));
        // pk is 65 bytes: 0x04 || X(32) || Y(32)
        assert_eq!(pk[0], 0x04, "not uncompressed SEC1");
        let qx = &pk[1..33];
        let qy = &pk[33..65];

        tests_json.push(format!(
            r#"        {{"tcId": {}, "d": "{}", "qx": "{}", "qy": "{}"}}"#,
            i + 1,
            hex_upper(d),
            hex_upper(qx),
            hex_upper(qy),
        ));
    }

    let json = format!(
        r#"{{
  "vsId": 0,
  "algorithm": "ECDSA",
  "mode": "keyGen",
  "revision": "FIPS186-5",
  "isSample": true,
  "testGroups": [
    {{
      "tgId": 1,
      "testType": "AFT",
      "curve": "P-256",
      "tests": [
{}
      ]
    }}
  ]
}}"#,
        tests_json.join(",\n"),
    );

    let out_dir = std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .unwrap()
        .join("vendor/nist/acvp-server/gen-val/json-files/ECDSA-keyGen-FIPS186-5");
    std::fs::create_dir_all(&out_dir).unwrap();
    let out_path = out_dir.join("kat-slice.json");
    let mut f = std::fs::File::create(&out_path).unwrap();
    f.write_all(json.as_bytes()).unwrap();
    println!("Wrote {}", out_path.display());
}
