//! Power-up known-answer tests for fips-drbg.
//!
//! # Source traceability
//!
//! All CTR_DRBG vectors in this module are reproduced verbatim from
//! the NIST CAVP DRBG validation vectors
//! (`drbgtestvectors/drbgvectors_no_reseed/CTR_DRBG.rsp`, CAVS 14.3)
//! vendored under `vendor/nist/cavp-drbg/`. Each KAT entry cites the
//! CAVS section header and `COUNT = 0` from that file.
//!
//! # Coverage
//!
//! For each AES key size (128, 192, 256) we exercise both CTR_DRBG
//! variants approved by SP 800-90A §10.2:
//!
//!   * `no df` — `instantiate_no_df` + two `generate_no_df` calls
//!   * `use df` — `instantiate_df` + two `generate_df` calls, which
//!     exercises `Block_Cipher_df` and `BCC` on the instantiate path.
//!
//! That's 6 KATs total. FIPS 140-3 IG 10.3.A requires exercising
//! every approved configuration of the DRBG at power-up; the `no df`
//! KATs cover the core Update/Generate state machine and the `use
//! df` KATs additionally cover the derivation function path.

