/// Compute the DH-3072 shared secret `Z = y_B ^ x_A mod p`.
///
/// # Errors
///
/// Returns [`Error::NotOperational`] if the containing FIPS module
/// has not finished its power-up self-tests,
/// [`Error::AlgorithmRestricted`] if the active profile does not
/// allow DH-3072, or [`Error::InvalidInput`] if `x` is not in
/// `[1, q − 1]`, `y` fails SP 800-56Ar3 §5.6.2.3.2 partial public-key
/// validation, or the shared secret `Z == 1`.
pub fn compute_shared_secret_3072(
    x_bytes: &[u8; KEY_BYTES],
    y_bytes: &[u8; KEY_BYTES],
) -> Result<[u8; KEY_BYTES], Error> {
    require_operational()?;
    require_allowed(Service::Dh3072)?;
    compute_shared_secret_3072_internal(x_bytes, y_bytes).ok_or(Error::InvalidInput)
}

/// Generate a DH-3072 key pair `(private_key, public_key)`.
///
/// The private key `x` is sampled from `[1, q − 1]` via
/// HMAC-DRBG-SHA-256 rejection sampling. The public key is
/// `y = 2^x mod p`.
///
/// # Errors
///
/// Returns [`Error::NotOperational`] if the FIPS module is not
/// operational, [`Error::AlgorithmRestricted`] if the active
/// profile does not allow DH-3072, or [`Error::InvalidInput`] if
/// key generation fails (DRBG failure or exhausted attempts).
pub fn generate_keypair_3072(
    drbg: &mut HmacDrbgSha256,
) -> Result<([u8; KEY_BYTES], [u8; KEY_BYTES]), Error> {
    require_operational()?;
    require_allowed(Service::Dh3072)?;
    generate_keypair_3072_internal(drbg).ok_or(Error::InvalidInput)
}

