//! Finite-field Diffie-Hellman key agreement (RFC 3526 Group 15).
//!
//! # Approved services
//!
//! | Service | Standard | Entry point |
//! |---------|----------|-------------|
//! | DH-3072 key agreement | SP 800-56Ar3 §5.7.1.1 | [`compute_shared_secret_3072`] |
//! | DH-3072 key-pair generation | SP 800-56Ar3 §5.6.1.1 | [`generate_keypair_3072`] |
//!
//! Both entry points operate over RFC 3526 Group 15 (3072-bit
//! MODP group, generator `g = 2`, safe prime `p`).
//!
//! # Key agreement primitive
//!
//! Implements the SP 800-56Ar3 §5.7.1.1 "Finite Field
//! Diffie-Hellman" (FFC DH) primitive:
//!
//! ```text
//!   Z = y_B ^ x_A  mod p
//! ```
//!
//! where `x_A` is the caller's private key, `y_B` is the peer's
//! public key, and `Z` is the raw shared secret (384 bytes).
//! The shared secret `Z` is raw; callers that need an approved
//! key-derivation step must feed `Z` into an SP 800-56Cr2
//! extractor — this crate does not bundle a KDF.
//!
//! # Public-key validation
//!
//! Peer public keys are validated per SP 800-56Ar3 §5.6.2.3.2
//! (partial public-key validation, sufficient for safe-prime groups
//! with cofactor `h = 2`):
//!
//! - `2 ≤ y ≤ p − 2`
//!
//! For safe-prime groups the cofactor is 2, so the only possible
//! small-subgroup element is `p − 1` (order 2), which the range
//! check excludes. No separate `y^q` check is needed (SP 800-56Ar3
//! §5.5.2). A peer key that fails the range check causes the
//! function to return an error *without* performing the private
//! exponentiation.
//!
//! # Key-pair generation
//!
//! [`generate_keypair_3072`] samples a private key
//! `x ∈ [1, q − 1]` from HMAC-DRBG-SHA-256 (rejection sampling)
//! and computes the public key `y = g^x mod p`.
//!
//! # Power-up self-tests
//!
//! [`self_test`] runs both directions of a deterministic KAT
//! (`x_A * y_B` and `x_B * y_A`) over externally generated
//! vectors and verifies that the order-2 element `p − 1` is rejected
//! by public-key validation.
//!
//! # Conditional self-tests
//!
//! Partial peer-public-key validation per SP 800-56Ar3 §5.6.2.3.2
//! is a conditional test that runs on every DH call.
//! Private-key range (`1 ≤ x < q`) is checked alongside.
//!
//! # Sensitive security parameters
//!
//! - **Private key `x`** (`[u8; 384]`) — CSP. Validated for
//!   range and used for the modular exponentiation, then not
//!   retained beyond the call.
//! - **Shared secret `Z`** (`[u8; 384]`) — CSP. Returned raw;
//!   the caller is responsible for feeding it into an SP 800-56Cr2
//!   extractor before use as keying material.
//! - **Peer public key `y`** — public. Subject to partial validation
//!   (SP 800-56Ar3 §5.6.2.3.2).
//!
//! # Side-channel posture
//!
//! The private exponentiation `y^x mod p` is computed via the
//! Montgomery `pow_secret` ladder (4-bit fixed-window, fixed
//! iteration count). Public-key
//! validation branches only on public data. Level-1 disclosure
//! only.
//!
//! # FIPS module gating
//!
//! Public entry points gate on
//! [`oxicrypt_module::require_operational`]; hidden `*_internal`
//! primitives bypass the gate so the power-up KATs can run while
//! the module is still in `SelfTest`.

