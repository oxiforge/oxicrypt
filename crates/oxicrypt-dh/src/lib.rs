// Key-pair generation (state-gate-free, for internal use)
// ------------------------------------------------------------------

/// Generate a DH-3072 key pair `(x, y)` where `x ∈ [1, q − 1]`
/// and `y = g^x mod p`.
///
/// Uses rejection sampling over 384-byte DRBG output: sample
/// `x_candidate`, mask the top bit to keep it < 2^3071, reject if
/// `x_candidate ∉ [1, q − 1]`. Rejection has probability about
/// `2^{-66}` per attempt (`2^3071 − q < 2^3005`), so
/// `KEYGEN_MAX_ATTEMPTS = 128` fails with probability far below
/// `2^{-128}`.
///
/// Returns `None` if the DRBG fails or if all attempts are
/// rejected (statistically impossible with a working DRBG).
#[doc(hidden)]
pub fn generate_keypair_3072_internal(
    drbg: &mut HmacDrbgSha256,
) -> Option<([u8; KEY_BYTES], [u8; KEY_BYTES])> {
    let q = U3072::from_be_bytes(&GROUP15_Q_BYTES);
    let one = U3072::from_be_bytes(&ONE_BYTES);
    let ctx = group15_mont_ctx()?;

    let mut buf = [0u8; KEY_BYTES];

    for _ in 0..KEYGEN_MAX_ATTEMPTS {
        if drbg.generate(None, &mut buf).is_err() {
            return None;
        }

        // Mask top bit so candidate < 2^3071 (q < 2^3071).
        buf[0] &= 0x7f;

        let x = U3072::from_be_bytes(&buf);

        // Reject x == 0 or x >= q.
        if x.is_zero() == 1 {
            continue;
        }
        if q.ct_lt(&x) == 1 || q.ct_eq(&x) == 1 {
            continue;
        }

        // y = g^x mod p. g = 2, so we use pow_secret with base = 2.
        // pow_secret handles to_mont/from_mont internally.
        let two = U3072::from_be_bytes(&TWO_BYTES);
        let y = ctx.pow_secret(&two, &x);

        // Sanity: y must not be 0 or 1 (impossible for valid x, but
        // defense in depth).
        if y.is_zero() == 1 || y.ct_eq(&one) == 1 {
            continue;
        }

        // Zero the buffer before returning, through
        // `oxicrypt-zeroize`'s volatile store so the write is not
        // elided on a local that is dead afterwards.
        oxicrypt_zeroize::zeroize(&mut buf);

        return Some((x.to_be_bytes(), y.to_be_bytes()));
    }

    None
}

