/// Compute the SP 800-56Ar3 §5.7.1.1 FFC DH primitive:
/// `Z = y_B ^ x_A mod p`.
///
/// Returns `None` when:
/// - `x` is not in `[1, q − 1]`
/// - `y` fails SP 800-56Ar3 §5.6.2.3.2 partial public-key validation
/// - `Z == 1` (SP 800-56Ar3 §5.7.1.1 error condition)
///
/// This function bypasses the FIPS module state gate so it can be
/// called from the power-up KAT runner; production callers should
/// use [`compute_shared_secret_3072`] instead.
#[doc(hidden)]
pub fn compute_shared_secret_3072_internal(
    x_bytes: &[u8; KEY_BYTES],
    y_bytes: &[u8; KEY_BYTES],
) -> Option<[u8; KEY_BYTES]> {
    let x = U3072::from_be_bytes(x_bytes);
    let q = U3072::from_be_bytes(&GROUP15_Q_BYTES);
    let one = U3072::from_be_bytes(&ONE_BYTES);

    // Private key must be in [1, q - 1].
    if x.is_zero() == 1 {
        return None;
    }
    // x < q (i.e. x <= q - 1).
    if q.ct_lt(&x) == 1 || q.ct_eq(&x) == 1 {
        return None;
    }

    let y = U3072::from_be_bytes(y_bytes);

    // Partial public-key validation per SP 800-56Ar3 §5.6.2.3.2.
    if !validate_public_key(&y) {
        return None;
    }

    // Z = y^x mod p via the Montgomery fixed-window ladder.
    // pow_secret handles the to_mont / from_mont conversion internally.
    let ctx = group15_mont_ctx()?;
    let z = ctx.pow_secret(&y, &x);

    // SP 800-56Ar3 §5.7.1.1: if Z == 1, output error.
    if z.ct_eq(&one) == 1 || z.is_zero() == 1 {
        return None;
    }

    Some(z.to_be_bytes())
}

