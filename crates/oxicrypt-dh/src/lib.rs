/// The value `1` as a `U3072` (used for the shared-secret != 1 check).
const ONE_BYTES: [u8; 384] = {
    let mut b = [0u8; 384];
    b[383] = 1;
    b
};

/// The value `2` as a `U3072` (lower bound for public-key validation).
const TWO_BYTES: [u8; 384] = {
    let mut b = [0u8; 384];
    b[383] = 2;
    b
};

/// Maximum rejection-sampling iterations for key generation before
/// returning an error. Candidates are masked to `< 2^3071` and rejected
/// only when outside `[1, q − 1]`; since `2^3071 − q < 2^3005`, rejection
/// has probability about `2^{-66}` per attempt, so 128 attempts fail with
/// probability far below `2^{-128}`.
const KEYGEN_MAX_ATTEMPTS: u32 = 128;

// ------------------------------------------------------------------
// Internal helpers
// ------------------------------------------------------------------

/// Build a `MontCtx3072` for the Group 15 prime.
///
/// Returns `None` only if `GROUP15_P` is even or zero, which cannot
/// happen (caught by tests). Production callers propagate the `None`
/// as an input-validation failure.
fn group15_mont_ctx() -> Option<MontCtx3072> {
    let p = U3072::from_be_bytes(&GROUP15_P_BYTES);
    MontCtx3072::new(p)
}

/// SP 800-56Ar3 §5.6.2.3.2 partial public-key validation for safe-prime
/// FFC groups (cofactor `h = 2`).
///
/// Returns `true` when `2 ≤ y ≤ p − 2`. For safe-prime groups this is
/// sufficient because the only small-subgroup element in `[2, p − 2]`
/// would need order dividing `h = 2`, and the sole order-2 element
/// `p − 1` is excluded by the upper bound.
fn validate_public_key(y: &U3072) -> bool {
    let two = U3072::from_be_bytes(&TWO_BYTES);
    let p = U3072::from_be_bytes(&GROUP15_P_BYTES);
    let one = U3072::from_be_bytes(&ONE_BYTES);

    // y >= 2.
    if y.ct_lt(&two) == 1 {
        return false;
    }

    // y <= p - 2, i.e. y < p - 1.
    let (p_minus_1, _) = p.subtracting(&one);
    if p_minus_1.ct_lt(y) == 1 || p_minus_1.ct_eq(y) == 1 {
        return false;
    }

    true
}

