static int failures = 0;

static void expect(const char *what, int rc, int want) {
    if (rc != want) {
        fprintf(stderr, "%s: rc=%d (expected %d)\n", what, rc, want);
        failures++;
    }
}

static void put_be32(uint8_t *at, uint32_t v) {
    at[0] = (uint8_t)(v >> 24);
    at[1] = (uint8_t)(v >> 16);
    at[2] = (uint8_t)(v >> 8);
    at[3] = (uint8_t)v;
}

int main(void) {
    /* Before initialisation: no verdict, whatever the inputs. */
    expect("verify before init",
           oxi_lms_verify(PK, ACCEPT_MSG, sizeof(ACCEPT_MSG), ACCEPT_SIG),
           RC_NOT_OPERATIONAL);
    expect("verify_any before init",
           oxi_lms_verify_any(PK, sizeof(PK), ACCEPT_MSG, sizeof(ACCEPT_MSG), ACCEPT_SIG,
                              sizeof(ACCEPT_SIG)),
           RC_NOT_OPERATIONAL);

    if (oxi_init(0) != 0) {
        fprintf(stderr, "oxi_init(Unrestricted) failed\n");
        return 1;
    }

    /* oxi_lms_verify: verdicts. */
    expect("verify(tcId 107)", oxi_lms_verify(PK, ACCEPT_MSG, sizeof(ACCEPT_MSG), ACCEPT_SIG),
           RC_OK);
    expect("verify(tcId 108)", oxi_lms_verify(PK, REJECT_MSG, sizeof(REJECT_MSG), REJECT_SIG),
           RC_TAG_MISMATCH);

    uint8_t sig[LMS_SIG_LEN];
    memcpy(sig, ACCEPT_SIG, sizeof(sig));
    sig[64] ^= 0x01;
    expect("verify(flipped bit)", oxi_lms_verify(PK, ACCEPT_MSG, sizeof(ACCEPT_MSG), sig),
           RC_TAG_MISMATCH);

    /* LMS_SHA256_M32_H5 (5), not H10 (6). */
    uint8_t pk_other[LMS_PK_LEN];
    memcpy(pk_other, PK, sizeof(pk_other));
    put_be32(pk_other, 0x00000005);
    expect("verify(public key of another pair)",
           oxi_lms_verify(pk_other, ACCEPT_MSG, sizeof(ACCEPT_MSG), ACCEPT_SIG),
           RC_TAG_MISMATCH);

    /* LMOTS_SHA256_N32_W1 (1), not W4 (3). */
    memcpy(sig, ACCEPT_SIG, sizeof(sig));
    put_be32(sig + 4, 0x00000001);
    expect("verify(signature with another LM-OTS typecode)",
           oxi_lms_verify(PK, ACCEPT_MSG, sizeof(ACCEPT_MSG), sig), RC_TAG_MISMATCH);

    memcpy(sig, ACCEPT_SIG, sizeof(sig));
    put_be32(sig + LMS_SIG_LMS_TYPE_AT, 0x00000005);
    expect("verify(signature with another LMS typecode)",
           oxi_lms_verify(PK, ACCEPT_MSG, sizeof(ACCEPT_MSG), sig), RC_TAG_MISMATCH);

    /* oxi_lms_verify_any: verdicts and lengths. */
    expect("verify_any(tcId 107)",
           oxi_lms_verify_any(PK, sizeof(PK), ACCEPT_MSG, sizeof(ACCEPT_MSG), ACCEPT_SIG,
                              sizeof(ACCEPT_SIG)),
           RC_OK);
    expect("verify_any(tcId 108)",
           oxi_lms_verify_any(PK, sizeof(PK), REJECT_MSG, sizeof(REJECT_MSG), REJECT_SIG,
                              sizeof(REJECT_SIG)),
           RC_TAG_MISMATCH);

    uint8_t pk_long[LMS_PK_LEN + 1];
    memcpy(pk_long, PK, sizeof(PK));
    pk_long[LMS_PK_LEN] = 0;
    expect("verify_any(public key one byte short)",
           oxi_lms_verify_any(PK, sizeof(PK) - 1, ACCEPT_MSG, sizeof(ACCEPT_MSG), ACCEPT_SIG,
                              sizeof(ACCEPT_SIG)),
           RC_INVALID_INPUT);
    expect("verify_any(public key one byte long)",
           oxi_lms_verify_any(pk_long, sizeof(pk_long), ACCEPT_MSG, sizeof(ACCEPT_MSG),
                              ACCEPT_SIG, sizeof(ACCEPT_SIG)),
           RC_INVALID_INPUT);

    uint8_t sig_long[LMS_SIG_LEN + 1];
    memcpy(sig_long, ACCEPT_SIG, sizeof(ACCEPT_SIG));
    sig_long[LMS_SIG_LEN] = 0;
    expect("verify_any(signature one byte short)",
           oxi_lms_verify_any(PK, sizeof(PK), ACCEPT_MSG, sizeof(ACCEPT_MSG), ACCEPT_SIG,
                              sizeof(ACCEPT_SIG) - 1),
           RC_INVALID_INPUT);
    expect("verify_any(signature one byte long)",
           oxi_lms_verify_any(PK, sizeof(PK), ACCEPT_MSG, sizeof(ACCEPT_MSG), sig_long,
                              sizeof(sig_long)),
           RC_INVALID_INPUT);

    /* NULL pointers: an error code, never a dereference. */
    expect("verify(NULL public key)",
           oxi_lms_verify(NULL, ACCEPT_MSG, sizeof(ACCEPT_MSG), ACCEPT_SIG), RC_NULL_POINTER);
    expect("verify(NULL message, non-zero length)",
           oxi_lms_verify(PK, NULL, sizeof(ACCEPT_MSG), ACCEPT_SIG), RC_NULL_POINTER);
    expect("verify(NULL signature)",
           oxi_lms_verify(PK, ACCEPT_MSG, sizeof(ACCEPT_MSG), NULL), RC_NULL_POINTER);
    expect("verify(NULL message, length 0)", oxi_lms_verify(PK, NULL, 0, ACCEPT_SIG),
           RC_TAG_MISMATCH);

    expect("verify_any(NULL public key)",
           oxi_lms_verify_any(NULL, sizeof(PK), ACCEPT_MSG, sizeof(ACCEPT_MSG), ACCEPT_SIG,
                              sizeof(ACCEPT_SIG)),
           RC_NULL_POINTER);
    expect("verify_any(NULL message, non-zero length)",
           oxi_lms_verify_any(PK, sizeof(PK), NULL, sizeof(ACCEPT_MSG), ACCEPT_SIG,
                              sizeof(ACCEPT_SIG)),
           RC_NULL_POINTER);
    expect("verify_any(NULL signature)",
           oxi_lms_verify_any(PK, sizeof(PK), ACCEPT_MSG, sizeof(ACCEPT_MSG), NULL,
                              sizeof(ACCEPT_SIG)),
           RC_NULL_POINTER);
    expect("verify_any(NULL message, length 0)",
           oxi_lms_verify_any(PK, sizeof(PK), NULL, 0, ACCEPT_SIG, sizeof(ACCEPT_SIG)),
           RC_TAG_MISMATCH);
    /* A NULL public key of length 0 names no pair. */
    expect("verify_any(NULL public key, length 0)",
           oxi_lms_verify_any(NULL, 0, ACCEPT_MSG, sizeof(ACCEPT_MSG), ACCEPT_SIG,
                              sizeof(ACCEPT_SIG)),
           RC_INVALID_INPUT);

    if (failures != 0) {
        fprintf(stderr, "test_lms_verify: %d check(s) failed\n", failures);
        return 1;
    }
    printf("test_lms_verify: OK (before-init refusal; verify verdicts and typecodes; "
           "verify_any verdicts and lengths; NULL pointers)\n");
    return 0;
}
