//! LMS (SP 800-208) — Leighton-Micali hash-based signatures, verification.
//!
//! Verifies LMS signatures for every (LMS, LM-OTS) parameter-set pair
//! that SP 800-208 approves: the SHA-256 sets of §4.1 (RFC 8554), and
//! the SHA-256/192, SHAKE256/256 and SHAKE256/192 sets of §4.2, §4.3 and
//! §4.4 (RFC 9858) — four hash families, five tree heights and four
//! Winternitz parameters, 80 pairs in all.
//!
//! # Verification only
//!
//! This crate implements signature verification and nothing else.
//! SP 800-208 §8.1 requires that implementations of LMS key generation
//! and signature generation be validated only within hardware
//! cryptographic modules at FIPS 140-3 Level 3 or higher physical
//! security. FIPS 140-3 IG C.N resolution 9 excludes software modules
//! from that, and resolution 6 bars offering a conforming scheme as a
//! non-approved service. Resolution 1 places a verify-only module under
//! §8.2, which requires at least one approved LM-OTS parameter set and
//! an LMS parameter set on the same hash function; this crate
//! implements all of them.
//!
//! Signing keys for the signatures verified here are therefore produced
//! elsewhere — in practice by a hardware module, which is the
//! deployment CNSA 2.0 anticipates for firmware signing.
//!
//! # Architecture — `lms_impl!` macro
//!
//! Every (LMS, LM-OTS) pair is generated by the `lms_impl!` macro from
//! one parameter tuple. A per-pair `lms_<family>_m<N>_h<H>_w<W>` module
//! invokes the macro and emits a self-contained verifier for that pair:
//! the LM-OTS public-key candidate computation (RFC 8554 §4.6) and the
//! Merkle authentication-path walk (RFC 8554 §5.4).
//!
//! Family-and-`N` divergence (SHA-256 / SHAKE256, output length 24 or
//! 32) is realised by a hash-adapter `:path` captured into the macro,
//! one concrete adapter per (family, N) shape in [`hash`]. There is no
//! nested sub-macro that dispatches on a `:literal` hash-family token.
//!
//! # Verifying under the pair a public key names
//!
//! [`verify_any`] reads the LMS and LM-OTS typecodes from a public key
//! and calls the `verify` of the per-pair module carrying them. The
//! routing table is generated by `scripts/lms_gen_pairs.py` from the
//! typecode tables that generate the per-pair modules. Input naming no
//! pair is refused as [`VerifyAnyError::Unroutable`], which is distinct
//! from [`VerifyAnyError::VerificationFailed`]. `verify_any` declares no
//! service of its own: the routed `verify` gates on its pair's service.
//!
//! # Approved services
//!
//! Each (LMS, LM-OTS) pair declares one `oxicrypt_module::Service`
//! discriminant, `Lms<Family>M<N>H<H>W<W>Verify`. The 80 discriminants
//! are the odd values 501-659.
//!
//! | Service group | Standard | Discriminants |
//! |---|---|---|
//! | SHA-256 / N=32 (20 pairs) | SP 800-208 §4.1 | odd values 501-539 |
//! | SHA-256 / N=24 (20 pairs) | SP 800-208 §4.2 | odd values 541-579 |
//! | SHAKE256 / N=32 (20 pairs) | SP 800-208 §4.3 | odd values 581-619 |
//! | SHAKE256 / N=24 (20 pairs) | SP 800-208 §4.4 | odd values 621-659 |
//!
//! CNSA 2.0 permits every one of the 80 pairs. CNSA 1.0 permits none of
//! them: CNSSP-15 (October 2016) names no stateful hash-based signature
//! scheme. `Migration` permits them, as the union of the two suites.
//! CNSSP-15 (2025) Annex B states "all parameters appropriate to protect to TOP
//! SECRET" for LMS, recommending LMS-SHA-256/192, and so places no subset
//! restriction on the parameter sets — see
//! `oxicrypt_module::is_allowed`.
//!
//! # Self-tests
//!
//! [`KATS`] holds four conditional algorithm self-tests (CASTs), one per
//! hash adapter: SHA-256/N=32, SHA-256/N=24, SHAKE256/N=32 and
//! SHAKE256/N=24, each on its H = 5, W = 1 pair, the cheapest
//! verification in the grid. Each CAST verifies a NIST ACVP sigVer
//! vector that NIST marks valid and rejects one from the same test group
//! that NIST marks invalid. The vectors and their provenance are in the
//! private `kat` module.
//!
//! # Sensitive security parameters (SSPs)
//!
//! None. A verifier reads only public values: the public key, the
//! message and the signature.
//!
//! # FIPS module gating
//!
//! Each pair's `verify` gates on `require_operational` and on its
//! `Service::Lms<…>Verify`.
//!
//! LMS is the one family the CNSA 2.0 profile admits by a discriminant
//! test rather than by enumerated arms, because CNSSP-15 (2025) Annex B
//! imposes no subset on it; CNSA 1.0 refuses every LMS service. So under
//! CNSA 2.0 the fail-safe default-deny that covers every other family
//! does **not** cover a new LMS pair: one added on an odd discriminant
//! inside the reserved block is automatically *permitted*, not denied.
//! That is the intended reading of the policy, and it is why
//! `oxicrypt_module`'s `lms_discriminant_slots_are_complete_and_pure`
//! exists — it fails if anything but LMS ever lands in the block, which
//! is the case the discriminant test cannot distinguish on its own.

