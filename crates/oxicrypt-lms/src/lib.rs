/// Known answer for one CAST: `accept` must verify and `reject` must not.
///
/// The reject case is a signature NIST marks invalid for its message, not
/// a bit flipped here. Without it, a verifier that accepted everything
/// would pass.
fn cast_verdict(
    accept: Result<bool, oxicrypt_module::Error>,
    reject: Result<bool, oxicrypt_module::Error>,
) -> Result<(), SelfTestFailure> {
    if accept == Ok(true) && reject == Ok(false) {
        Ok(())
    } else {
        Err(SelfTestFailure)
    }
}

/// CAST for the SHA-256 / N=32 adapter.
fn cast_sha256_n32() -> Result<(), SelfTestFailure> {
    use lms_sha256_m32_h5_w1::verify_internal as v;
    cast_verdict(
        v(
            &kat::SHA256_N32_PUBLIC_KEY,
            &kat::SHA256_N32_ACCEPT_MSG,
            &kat::SHA256_N32_ACCEPT_SIG,
        ),
        v(
            &kat::SHA256_N32_PUBLIC_KEY,
            &kat::SHA256_N32_REJECT_MSG,
            &kat::SHA256_N32_REJECT_SIG,
        ),
    )
}

