//! Power-up known-answer tests for fips-drbg.
//!
//! # Source traceability
//!
//! All DRBG vectors in this module are reproduced verbatim from the
//! NIST CAVP DRBG validation vectors (CAVS 14.3), vendored under
//! `vendor/nist/cavp-drbg/`:
//!
//!   * `no_reseed/{CTR_DRBG,Hash_DRBG,HMAC_DRBG}.rsp` — value-level
//!     KATs exercising instantiate + two generate calls without
//!     prediction resistance.
//!   * `pr_true/{CTR_DRBG,Hash_DRBG,HMAC_DRBG}.rsp` — value-level
//!     KATs exercising instantiate + two PR-generate calls per
//!     SP 800-90A §9.3.
//!
//! Each KAT entry cites the CAVS section header and `COUNT = 0`
//! from the source file.  Per-KAT SHA-256 traceability is in
//! `docs/cavp-mapping/drbg.md`.
//!
//! # Coverage
//!
//! For each AES key size (128, 192, 256) we exercise both CTR_DRBG
//! variants approved by SP 800-90A §10.2:
//!
//!   * `no df` — `instantiate_no_df` + two `generate_no_df` calls
//!   * `use df` — `instantiate_df` + two `generate_df` calls, which
//!     exercises `Block_Cipher_df` and `BCC` on the instantiate path.
//!
//! For Hash_DRBG (SP 800-90A §10.1.1) and HMAC_DRBG (SP 800-90A
//! §10.1.2) we exercise each approved SHA-2 digest (SHA-256, SHA-384,
//! SHA-512) with `instantiate` + two `generate` calls. The Hash_DRBG
//! path drives `Hash_df` (§10.3.1) and the `Hashgen` update loop; the
//! HMAC_DRBG path drives the `HMAC_DRBG_Update` helper and the
//! `V = HMAC(K, V)` output loop.
//!
//! On top of the value-level KATs, three SP 800-90A §11.3 health
//! tests (CTR_DRBG, Hash_DRBG, HMAC_DRBG) run the error paths
//! required by §11.3.2 — generate-before-instantiate, reseed-counter
//! ceiling, and post-uninstantiate access — from [`crate::health`].
//!
//! On top of the non-PR value-level KATs, nine prediction-resistance
//! KATs (3 CTR use df, 3 Hash, 3 HMAC) exercise the SP 800-90A §9.3
//! reseed-then-generate path via the `generate_pr` / `generate_df_pr`
//! wrappers on each DRBG.
//!
//! That's 24 KATs total. FIPS 140-3 IG 10.3.A requires exercising
//! every approved configuration of the DRBG at power-up; the `no df`
//! KATs cover the core Update/Generate state machine, the `use df`
//! KATs additionally cover the derivation function path, the
//! Hash/HMAC_DRBG KATs cover two separate SP 800-90A mechanisms, the
//! PR KATs cover the §9.3 prediction-resistance reseed path, and the
//! health tests cover the §11.3.2 error-path requirements.

